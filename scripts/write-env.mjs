// Writes .env.local from the running local Supabase stack (`npx supabase start` must be running).
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const raw = execSync("npx supabase status -o json", { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
const s = JSON.parse(raw.slice(raw.indexOf("{")));

const env = `# Generated by \`npm run env\` from the local Supabase stack. Safe to regenerate.
NEXT_PUBLIC_SUPABASE_URL=${s.API_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${s.ANON_KEY}
SUPABASE_SERVICE_ROLE_KEY=${s.SERVICE_ROLE_KEY}
SITE_URL=http://localhost:3000
SMTP_HOST=127.0.0.1
SMTP_PORT=54325
EMAIL_FROM="Amherst Woods Board <board@amherstwoods.local>"
`;
writeFileSync(new URL("../.env.local", import.meta.url), env);
console.log("Wrote .env.local");
console.log(`Mailpit (local inbox): ${s.MAILPIT_URL ?? s.INBUCKET_URL ?? "http://127.0.0.1:54324"}`);
console.log(`Supabase Studio:       ${s.STUDIO_URL}`);
